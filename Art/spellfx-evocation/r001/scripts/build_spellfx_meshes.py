"""Write the low-poly spell VFX source meshes (OBJ, centimetres, flat faces) for spellfx-evocation r001.

Run: python Art/spellfx-evocation/r001/scripts/build_spellfx_meshes.py
Deterministic: same output bytes on every run. No third-party content.
"""
import math
import os

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def write(name, verts, faces):
    lines = ["# " + name + " - dnd-diceroll spellfx-evocation r001, generated by build_spellfx_meshes.py", "o " + name]
    normals = []
    for face in faces:
        a, b, c = (verts[i] for i in face[:3])
        u = [b[k] - a[k] for k in range(3)]
        v = [c[k] - a[k] for k in range(3)]
        n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
        length = math.sqrt(sum(x * x for x in n)) or 1.0
        normals.append([x / length for x in n])
    for p in verts:
        lines.append("v %.4f %.4f %.4f" % tuple(p))
    for n in normals:
        lines.append("vn %.4f %.4f %.4f" % tuple(n))
    lines.append("vt 0 0")
    for index, face in enumerate(faces):
        lines.append("f " + " ".join("%d/1/%d" % (i + 1, index + 1) for i in face))
    with open(os.path.join(OUT, name + ".obj"), "w", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


def ico(radius=50.0):
    t = (1.0 + math.sqrt(5.0)) / 2.0
    raw = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
           (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
    scale = radius / math.sqrt(1 + t * t)
    verts = [[x * scale, y * scale, z * scale] for x, y, z in raw]
    faces = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
             (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1)]
    return verts, faces


def shard():
    # Elongated hexagonal bipyramid along +X: nose at +60, tail at -40, waist radius 14.
    verts = [[60.0, 0.0, 0.0], [-40.0, 0.0, 0.0]]
    for k in range(6):
        a = k * math.pi / 3.0
        verts.append([8.0, 14.0 * math.cos(a), 14.0 * math.sin(a)])
    faces = []
    for k in range(6):
        i, j = 2 + k, 2 + (k + 1) % 6
        faces.append((0, i, j))
        faces.append((1, j, i))
    return verts, faces


def cell_frame():
    # One grid cell outline in XY (100 cm outer, 78 cm inner), facing +Z.
    o, i = 50.0, 39.0
    verts = [[-o, -o, 0], [o, -o, 0], [o, o, 0], [-o, o, 0], [-i, -i, 0], [i, -i, 0], [i, i, 0], [-i, i, 0]]
    faces = []
    for k in range(4):
        a, b = k, (k + 1) % 4
        faces.append((a, b, 4 + b))
        faces.append((a, 4 + b, 4 + a))
    return verts, faces


if __name__ == "__main__":
    write("SM_SpellFX_Ico", *ico())
    write("SM_SpellFX_Shard", *shard())
    write("SM_SpellFX_CellFrame", *cell_frame())
    print("wrote 3 meshes to " + OUT)
